// Builds docs/integrations/verify-installed-all.sql from the individual metadata
// checkers (one SELECT for the TEST DB SQL Editor) and proves it on PGlite.
//   node scripts/verify-combined-checker.cjs --write   regenerate the combined file
//   node scripts/verify-combined-checker.cjs           check it is in sync + run it
// Metadata only: no customer rows, RPC calls or writes. No network, no env file.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {createPurchaseDatabase} = require('./fixtures/purchase-database.cjs');

const DOCS = path.join(__dirname, '../../../docs/integrations');
const OUT = path.join(DOCS, 'verify-installed-all.sql');
// Install order (see 30-live-readiness.md). component → checker file.
const PARTS = [
  ['1_foundation', 'verify-installed-foundation.sql'],
  ['2_purchase', 'verify-installed-purchase.sql'],
  ['3_notifications_merchant_queue', 'verify-installed-delivery-features.sql'],
  ['4_notification_source', 'verify-installed-notification-source.sql'],
  ['5_shipment_notifications', 'verify-installed-shipment-notifications.sql'],
  ['6_merchant_fence', 'verify-installed-merchant-fence.sql'],
  ['7_catalog_fts', 'verify-installed-catalog-search.sql'],
  ['8_search_console_store', 'verify-installed-search-console-store.sql'],
  ['9_pagespeed_store', 'verify-installed-pagespeed-store.sql'],
  ['10_ops_metrics', 'verify-installed-ops-metrics.sql'],
  ['11_live_usage', 'verify-installed-live-usage.sql'],
];
function body(file) {
  const sql = fs.readFileSync(path.join(DOCS, file), 'utf8')
    .split('\n').filter(line => !/^\s*--/.test(line)).join('\n').trim().replace(/;\s*$/, '');
  assert.ok(!sql.includes(';'), file + ' must be a single statement');
  return sql;
}
function build() {
  const parts = PARTS.map(([component, file], i) =>
    `  SELECT ${i + 1} AS step, '${component}' AS component, c.check_name, c.status FROM (\n` +
    body(file).split('\n').map(l => '    ' + l).join('\n') + `\n  ) AS c(check_name, status)`);
  return `-- GENERATED by apps/api/scripts/verify-combined-checker.cjs --write. Do not edit by hand.
-- One read-only metadata SELECT for the TEST DB SQL Editor: every integration package,
-- in install order. CHUA_CAI = not installed (fine if you do not use that feature),
-- PASS = installed with private grants, FAIL = paused on purpose or misconfigured.
-- No customer rows are read, no RPC is executed, nothing is written.
SELECT component, check_name, status FROM (
${parts.join('\n  UNION ALL\n')}
) AS all_checks
ORDER BY step, check_name;
`;
}

(async () => {
  const sql = build();
  if (process.argv.includes('--write')) {fs.writeFileSync(OUT, sql); console.log('WROTE ' + path.relative(process.cwd(), OUT)); return;}
  assert.equal(fs.readFileSync(OUT, 'utf8'), sql, 'verify-installed-all.sql is stale: run with --write');
  const db = await createPurchaseDatabase();
  let checks = 1;
  try {
    const run = async () => (await db.query(sql)).rows;
    const byComponent = rows => rows.reduce((m, r) => ((m[r.component] ??= new Set()).add(r.status), m), {});
    const before = await run();
    assert.equal(new Set(before.map(r => r.component)).size, PARTS.length); checks++;
    // Fixture has foundation + purchase only; everything else is not installed yet.
    for (const [component] of PARTS.slice(3)) {
      if (component === '7_catalog_fts') continue; // needs catalog tables absent from fixture
      assert.deepEqual([...byComponent(before)[component]], ['CHUA_CAI'], component); checks++;
    }
    assert.deepEqual([...byComponent(before)['2_purchase']], ['PASS']); checks++;
    for (const file of ['integration-notifications.sql', 'integration-merchant-queue.sql', 'integration-merchant-fence.sql',
      'search-console-durable-mock.sql', 'pagespeed-durable-mock.sql', 'integration-ops-metrics.sql'])
      await db.exec(fs.readFileSync(path.join(__dirname, '../migrations', file), 'utf8'));
    const after = byComponent(await run());
    for (const component of ['2_purchase', '6_merchant_fence', '8_search_console_store', '9_pagespeed_store', '10_ops_metrics']) {
      assert.deepEqual([...after[component]], ['PASS'], component); checks++;
    }
    // Delivery-features mixes notification (installed) and merchant queue RPCs (installed): PASS only.
    assert.deepEqual([...after['3_notifications_merchant_queue']].sort(), ['PASS']); checks++;
    await db.exec(fs.readFileSync(path.join(__dirname, '../migrations/integration-ops-metrics.pause.sql'), 'utf8'));
    assert.deepEqual([...byComponent(await run())['10_ops_metrics']], ['FAIL']); checks++;
    const report = {result: 'PASS', checks, components: PARTS.length, inSync: true, readOnly: true, hostedRequests: 0};
    console.log(JSON.stringify(report));
  } finally {await db.close();}
})().catch(e => {console.error('COMBINED_CHECKER_FAILED', e?.message ?? ''); process.exitCode = 1;});
