// Builds apps/api/migrations/test-db-core-bundle.sql: the core integration packages
// concatenated in install order, each still its own BEGIN/COMMIT, behind a guard that
// refuses a non-Supabase DB, a DB without orders, or any partially installed state.
//   node scripts/build-test-db-bundle.cjs --write   regenerate
//   node scripts/build-test-db-bundle.cjs           check in sync + prove on PGlite
// No network, no env file, no hosted DB.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const {PGlite} = require('@electric-sql/pglite');

const MIGRATIONS = path.join(__dirname, '../migrations');
const OUT = path.join(MIGRATIONS, 'test-db-core-bundle.sql');
const CHECKER = path.join(__dirname, '../../../docs/integrations/verify-installed-all.sql');
// Core only. NOT included on purpose: integration-notification-source.sql and
// integration-shipment-notifications.sql (triggers on business tables) and
// catalog-full-text-search.sql (index build on catalog) — install those separately.
const FILES = ['integration-delivery-foundation.sql', 'integration-purchase-capture.sql', 'integration-notifications.sql',
  'integration-merchant-queue.sql', 'integration-merchant-fence.sql', 'search-console-durable-mock.sql',
  'pagespeed-durable-mock.sql', 'integration-ops-metrics.sql'];
const GUARD_OBJECTS = [
  ['table', 'public.integration_outbox'], ['table', 'public.integration_usage_daily'],
  ['function', 'public.integration_record_purchase_mock(uuid,uuid,boolean)'],
  ['function', 'public.integration_capture_notification_mock(uuid,text)'],
  ['function', 'public.integration_enqueue_merchant_mock(uuid,text,text)'],
  ['table', 'public.integration_merchant_send_fence'], ['table', 'public.seo_search_sync_state'],
  ['table', 'public.seo_pagespeed_audit_state'], ['function', 'public.integration_ops_metrics_mock(integer)'],
];

function build() {
  const guard = GUARD_OBJECTS.map(([kind, name]) =>
    `    OR ${kind === 'table' ? 'to_regclass' : 'to_regprocedure'}('${name}') IS NOT NULL`).join('\n');
  const parts = FILES.map((file, i) => {
    const sql = fs.readFileSync(path.join(MIGRATIONS, file), 'utf8').trim();
    assert.ok(/^BEGIN;$/m.test(sql) && /COMMIT;$/.test(sql), file + ' must be one BEGIN/COMMIT package');
    return `-- ===== ${i + 1}/${FILES.length} ${file} =====\n${sql}`;
  });
  return `-- GENERATED by apps/api/scripts/build-test-db-bundle.cjs --write. Do not edit by hand.
-- TEST DB ONLY (Supabase SQL Editor of the test project, never production).
-- Installs, in order: ${FILES.join(', ')}.
-- Each package is its own transaction. Afterwards run docs/integrations/verify-installed-all.sql.
-- If anything fails: stop, copy the error message, run the checker; do NOT re-run blindly.
-- Pause any package later with its .pause.sql (revokes RPCs only, keeps data).
DO $bundle_guard$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='service_role')
    OR NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname='anon') THEN
    RAISE EXCEPTION 'BUNDLE_REFUSED_NOT_SUPABASE: service_role/anon roles not found';
  END IF;
  IF to_regclass('public.orders') IS NULL THEN
    RAISE EXCEPTION 'BUNDLE_REFUSED_NO_ORDERS_TABLE: wrong database?';
  END IF;
  IF false
${guard}
  THEN
    RAISE EXCEPTION 'BUNDLE_REFUSED_ALREADY_PARTLY_INSTALLED: run verify-installed-all.sql and install the remaining files one by one';
  END IF;
END
$bundle_guard$;

${parts.join('\n\n')}
`;
}

async function freshDb({orders = true} = {}) {
  const db = new PGlite();
  await db.exec('CREATE ROLE anon; CREATE ROLE authenticated; CREATE ROLE service_role BYPASSRLS; GRANT USAGE ON SCHEMA public TO anon,authenticated,service_role;');
  if (orders) await db.exec('CREATE TABLE public.orders(id uuid PRIMARY KEY,user_id uuid,status text,payment_status text,payment_method text,transaction_code text,total numeric,voucher_discount_amount numeric,items jsonb,shipping_info jsonb); GRANT ALL ON public.orders TO service_role;');
  return db;
}
const statuses = async db => {
  const rows = (await db.query(fs.readFileSync(CHECKER, 'utf8'))).rows;
  return rows.reduce((m, r) => ((m[r.component] ??= new Set()).add(r.status), m), {});
};
const objectCount = async db => Number((await db.query(
  "SELECT (SELECT count(*) FROM pg_proc p JOIN pg_namespace n ON n.oid=p.pronamespace WHERE n.nspname='public')+(SELECT count(*) FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace WHERE n.nspname='public') AS n")).rows[0].n);

(async () => {
  const sql = build();
  if (process.argv.includes('--write')) {fs.writeFileSync(OUT, sql); console.log('WROTE ' + path.relative(process.cwd(), OUT)); return;}
  assert.equal(fs.readFileSync(OUT, 'utf8'), sql, 'test-db-core-bundle.sql is stale: run with --write');
  let checks = 1;
  // 1. Clean Supabase-like DB: whole bundle installs; checker shows the expected packages.
  const db = await freshDb();
  try {
    await db.exec(sql);
    const s = await statuses(db);
    for (const c of ['2_purchase', '3_notifications_merchant_queue', '6_merchant_fence', '8_search_console_store', '9_pagespeed_store', '10_ops_metrics']) {
      assert.deepEqual([...s[c]], ['PASS'], c); checks++;
    }
    // Foundation integration checks PASS; user/post/contact checks need tables absent here.
    const foundation = (await db.query(fs.readFileSync(CHECKER, 'utf8'))).rows.filter(r => r.component === '1_foundation');
    for (const name of ['outbox_private_and_rls_enabled', 'usage_private_and_rls_enabled', 'claim_rpc_service_only', 'finish_rpc_service_only', 'quota_rpc_service_only']) {
      assert.equal(foundation.find(r => r.check_name === name).status, 'PASS', name); checks++;
    }
    for (const c of ['4_notification_source', '5_shipment_notifications']) {assert.deepEqual([...s[c]], ['CHUA_CAI'], c); checks++;}
    // 2. Re-running refuses up front and changes nothing.
    const before = await objectCount(db);
    await assert.rejects(db.exec(sql), e => /BUNDLE_REFUSED_ALREADY_PARTLY_INSTALLED/.test(e.message)); checks++;
    assert.equal(await objectCount(db), before); checks++;
  } finally {await db.close();}
  // 3. Partly installed (foundation only) → refused, nothing added.
  const partial = await freshDb();
  try {
    await partial.exec(fs.readFileSync(path.join(MIGRATIONS, FILES[0]), 'utf8'));
    const before = await objectCount(partial);
    await assert.rejects(partial.exec(sql), e => /ALREADY_PARTLY_INSTALLED/.test(e.message)); checks++;
    assert.equal(await objectCount(partial), before); checks++;
  } finally {await partial.close();}
  // 4. Wrong database (no orders table) → refused, nothing created.
  const wrong = await freshDb({orders: false});
  try {
    const before = await objectCount(wrong);
    await assert.rejects(wrong.exec(sql), e => /BUNDLE_REFUSED_NO_ORDERS_TABLE/.test(e.message)); checks++;
    assert.equal(await objectCount(wrong), before); checks++;
  } finally {await wrong.close();}
  console.log(JSON.stringify({result: 'PASS', checks, packages: FILES.length, inSync: true, hostedRequests: 0}));
})().catch(e => {console.error('BUNDLE_CHECK_FAILED', e?.message ?? ''); process.exitCode = 1;});
