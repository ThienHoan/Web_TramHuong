// Exact SQL in PostgreSQL memory. No env, network, real mail or order mutation.
const {readFileSync,writeFileSync}=require('node:fs');
const {join}=require('node:path');
const assert=require('node:assert/strict');
const {createPurchaseDatabase,seedOrder,ORDER,OWNER}=require('./fixtures/purchase-database.cjs');
const sql=readFileSync(join(__dirname,'../migrations/integration-notifications.sql'),'utf8');
const pause=readFileSync(join(__dirname,'../migrations/integration-notifications.pause.sql'),'utf8');
(async()=>{
 const db=await createPurchaseDatabase();let checks=0;
 const equal=(a,b)=>{assert.deepEqual(a,b);checks++;};
 const denied=async(fn,code)=>{await assert.rejects(fn,e=>e.code===code);checks++;};
 const capture=async(event='payment_success',order=ORDER)=>(await db.query('SELECT integration_capture_notification_mock($1,$2) AS r',[order,event])).rows[0].r;
 const claim=async()=>(await db.query("SELECT * FROM integration_claim('resend','mock',10,120)")).rows;
 const resolve=async(r)=>(await db.query('SELECT integration_resolve_notification_mock($1,$2,$3) AS r',[r.id,r.lease_token,r.version])).rows[0].r;
 try{
  await db.exec(sql);checks++;
  await seedOrder(db,ORDER,{shipping_info:{email:'customer@example.invalid',address:'PRIVATE_ADDRESS',phone:'PRIVATE_PHONE'}});
  const before=(await db.query('SELECT * FROM orders')).rows;
  await db.exec('SET ROLE service_role');
  const notices=await Promise.all(Array.from({length:6},()=>capture()));
  equal(notices.filter(r=>r.status==='recorded').length,1);
  equal(notices.filter(r=>r.status==='duplicate').length,5);
  equal(new Set(notices.map(r=>r.id)).size,1);
  const stored=(await db.query('SELECT * FROM integration_outbox')).rows[0];
  equal(stored.state,'QUEUED');equal(stored.operation_kind,'mutation');
  equal(Object.keys(stored.payload).sort(),['binding','event','orderId','status']);
  equal(JSON.stringify(stored.payload).includes('example.invalid'),false);
  equal(JSON.stringify(stored.payload).includes('PRIVATE'),false);
  const leased=(await claim())[0];
  equal((await resolve(leased)).mail.to,'customer@example.invalid');
  equal((await resolve(leased)).mail.template,'payment-success');
  equal((await resolve(leased)).mail.context,{id:ORDER,total:230000});
  await denied(()=>resolve({...leased,version:leased.version+1}),'PT409');
  await denied(()=>resolve({...leased,lease_token:OWNER}),'PT409');
  await db.query("UPDATE orders SET shipping_info=jsonb_build_object('email','other@example.invalid') WHERE id=$1",[ORDER]);
  await denied(()=>resolve(leased),'PT409');await denied(()=>capture(),'PT409');
  await db.query("UPDATE orders SET shipping_info=jsonb_build_object('email','customer@example.invalid'),status='SHIPPED' WHERE id=$1",[ORDER]);
  equal((await resolve(leased)).mail.to,'customer@example.invalid');
  const status=await capture('order_status');equal(status.status,'recorded');
  const statusLease=(await claim())[0];equal((await resolve(statusLease)).mail.context.status,'SHIPPED');
  await db.query("UPDATE orders SET status='COMPLETED' WHERE id=$1",[ORDER]);
  await denied(()=>resolve(statusLease),'PT409');
  equal((await capture('order_status')).status,'recorded');
  await db.query("UPDATE orders SET payment_status='pending' WHERE id=$1",[ORDER]);
  equal((await capture()).status,'not_eligible');await denied(()=>resolve(leased),'PT409');
  await db.query("UPDATE orders SET payment_status='paid',payment_method='cod' WHERE id=$1",[ORDER]);
  equal((await capture()).status,'not_eligible');
  await db.query("UPDATE orders SET payment_method='sepay',status='CANCELED' WHERE id=$1",[ORDER]);
  equal((await capture()).status,'not_eligible');equal((await capture('order_confirmation')).status,'not_eligible');
  await denied(()=>capture('invalid_event'),'22023');
  await denied(()=>capture('order_status',OWNER),'PT404');
  await db.query("UPDATE orders SET status='PAID',shipping_info=jsonb_build_object('email',E'bad\nheader@example.invalid') WHERE id=$1",[ORDER]);
  await denied(()=>capture(),'PT422');
  await db.exec('RESET ROLE');
  await db.query('UPDATE orders SET status=$2,payment_status=$3,payment_method=$4,shipping_info=$5 WHERE id=$1',[ORDER,'PAID','paid','sepay',JSON.stringify(before[0].shipping_info)]);
  equal((await db.query('SELECT * FROM orders')).rows,before);
  await db.exec('SET ROLE anon');await denied(()=>capture(),'42501');await denied(()=>resolve(leased),'42501');
  await db.exec('RESET ROLE; SET ROLE authenticated');await denied(()=>capture(),'42501');
  await db.exec('RESET ROLE');await denied(()=>db.exec(sql),'42723');await db.exec('ROLLBACK');
  const rows=(await db.query('SELECT count(*)::int AS n FROM integration_outbox')).rows[0].n;
  await db.exec(pause);await db.exec('SET ROLE service_role');await denied(()=>capture(),'42501');await denied(()=>resolve(leased),'42501');
  equal((await db.query('SELECT count(*)::int AS n FROM integration_outbox')).rows[0].n,rows);
  const report={batch:'P4-02a',engine:'in-memory PostgreSQL',checks,schema:'PASS',pause:'PASS',duplicateCaptures:5,atomicityScope:'committed_snapshot_capture_and_publication_not_original_order_write',hostedWrites:0,realEmails:0,remoteRequests:0};
  if(process.argv[2])writeFileSync(process.argv[2],JSON.stringify(report,null,2)+'\n');console.log(JSON.stringify(report));
 }finally{await db.close();}
})().catch(error=>{console.error(error.message);process.exitCode=1;});
