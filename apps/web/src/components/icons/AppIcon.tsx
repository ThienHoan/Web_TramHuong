interface AppIconProps extends Omit<LucideProps, "children"> {
  name: string;
  title?: string;
}
export function AppIcon({
  name,
  className,
  size,
  title,
  style,
  ...props
}: AppIconProps) {
  const Icon = APP_ICONS[name as keyof typeof APP_ICONS] || CircleHelp;
  const filled = name === "star" || name === "bookmark";
  return (
    <Icon
      aria-hidden={props["aria-label"] || title ? undefined : true}
      role={title ? "img" : undefined}
      focusable="false"
      size={size ?? "1em"}
      strokeWidth={1.65}
      fill={filled ? "currentColor" : "none"}
      className={cn("app-icon", className)}
      style={style}
      {...props}
    >
      {title && <title>{title}</title>}
    </Icon>
  );
}
